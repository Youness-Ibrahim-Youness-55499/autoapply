type LocaleContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
};

const LocaleContext = createContext<LocaleContextValue>({
  locale: "en",
  setLocale: () => {},
  t: (key) => key,
});

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>("en");

  useEffect(() => {
    const stored = localStorage.getItem("autoapply_locale");
    if (stored === "de") {
      setLocale("de");
    }
  }, []);

  useEffect(() => {
    localStorage.setItem("autoapply_locale", locale);
  }, [locale]);

  const value = useMemo<LocaleContextValue>(() => ({
    locale,
    setLocale,
    t: (key, vars) => {
      const translation = messages[locale][key] ?? messages.en[key] ?? key;
      if (!vars) return translation;
      return Object.entries(vars).reduce(
        (result, [variable, replacement]) =>
          result.replace(`{${variable}}`, String(replacement)),
        translation,
      );
    },
  }), [locale]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useTranslation() {
  return useContext(LocaleContext);
}
