revoke all on table public.job_boards from anon, authenticated;
revoke all on table public.jobs from anon, authenticated;
revoke all on table public.job_sources from anon, authenticated;
revoke all on table public.job_ingestion_runs from anon, authenticated;
revoke all on table public.job_skills_catalog from anon, authenticated;
revoke all on table public.job_skill_links from anon, authenticated;
revoke all on table public.job_raw_snapshots from anon, authenticated;

grant select on table public.job_companies to authenticated;
grant select on table public.jobs to authenticated;
grant all on table public.job_companies to service_role;
grant all on table public.job_boards to service_role;
grant all on table public.jobs to service_role;
grant all on table public.job_sources to service_role;
grant all on table public.job_ingestion_runs to service_role;
grant all on table public.job_skills_catalog to service_role;
grant all on table public.job_skill_links to service_role;
grant all on table public.job_raw_snapshots to service_role;
grant usage, select on sequence public.job_companies_id_seq to service_role;
grant usage, select on sequence public.job_boards_id_seq to service_role;
grant usage, select on sequence public.jobs_id_seq to service_role;
grant usage, select on sequence public.job_sources_id_seq to service_role;
