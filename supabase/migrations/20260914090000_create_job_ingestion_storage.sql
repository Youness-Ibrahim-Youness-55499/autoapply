create policy "Signed-in users can read job companies"
on public.job_companies
for select
to authenticated
using (true);

create policy "Signed-in users can read active jobs"
on public.jobs
for select
to authenticated
using (status = 'active');

comment on table public.job_sources is
  'Private ATS source occurrences and raw provider payloads; server-side access only.';
comment on table public.job_ingestion_runs is
  'Private operational diagnostics for the ATS ingestion worker.';
comment on table public.job_raw_snapshots is
  'Optional private source snapshots; no browser access.';
